// Release signing lives in a local, gitignored keystore.properties (see
// keystore.properties.example). Absent on a fresh checkout or CI without
// secrets configured - the release build type simply stays unsigned then,
// it never fails the build.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

android {
    namespace = "com.yighy.pantograph"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.yighy.pantograph"
        minSdk = 31
        targetSdk = 37
        versionCode = 6
        versionName = "0.13.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // R8: dead-code elimination, renaming and resource shrinking.
            // Release-only - always smoke-test the RELEASE apk before shipping.
            optimization {
                enable = true
            }
            if (keystorePropertiesFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
        // VERSION_NAME is read at runtime to decide whether the database may still fall back
        // to a destructive migration - see SchemaPolicy.
        buildConfig = true
    }
}

